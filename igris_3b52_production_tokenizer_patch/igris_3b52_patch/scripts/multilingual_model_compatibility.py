"""IGRIS Phase 16 — Multilingual Model Compatibility Verification.

Validates that the IGRIS transformer model seamlessly ingests token sequences
generated by Candidate A and Candidate B tokenizers across all 9 supported languages:
English, Hindi, Tamil, Telugu, Malayalam, Kannada, Bengali, Gujarati, and Tanglish.
"""
from __future__ import annotations

import hashlib
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

# Setup patch paths
_PATCH_ROOT = Path(__file__).resolve().parents[1]
_PATCH_SRC = str(_PATCH_ROOT / "src")
_PATCH_SCRIPTS = str(_PATCH_ROOT / "scripts")
for p in [_PATCH_SRC, _PATCH_SCRIPTS]:
    if p not in sys.path:
        sys.path.insert(0, p)

import torch
from igris.model.transformer import (
    IgrisConfig,
    IgrisDecoderTransformer,
    get_test_tiny_config,
)
from igris.tokenizer.strict import (
    STRUCTURAL_COUNT,
    STRUCTURAL_TOKENS,
    VOCAB_SIZE,
    load_candidate_a,
    load_candidate_b,
)
from tokenizer_multilingual_benchmark import BENCHMARK_SAMPLES, BenchmarkSample

CAND_A_PATH = _PATCH_ROOT / "artifacts" / "tokenizer" / "candidate_a" / "tokenizer.json"
CAND_B_PATH = _PATCH_ROOT / "artifacts" / "tokenizer" / "candidate_b" / "tokenizer.model"
CAND_A_HASH = "ac7e18b13973450b43bfff18609a833e4ef0e642b8dc5803e39ab1e81ba4c561"
CAND_B_HASH = "d3a3431e07c87ecce863647202ddc9b47b964718adbae7bf2bb2459223b94888"


@dataclass
class LanguageCompatibilityRecord:
    category: str
    sample_id: str
    cand_a_token_count: int
    cand_b_token_count: int
    ids_in_bounds: bool
    structural_ids_valid: bool
    forward_pass_passed: bool
    loss_finite: bool


@dataclass
class MultilingualCompatibilityReport:
    total_samples_evaluated: int
    all_in_bounds: bool
    batched_forward_pass_passed: bool
    padding_mask_loss_valid: bool
    candidate_a_hash_invariant: bool
    candidate_b_hash_invariant: bool
    per_sample_records: list[LanguageCompatibilityRecord]
    notes: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "total_samples_evaluated": self.total_samples_evaluated,
            "all_in_bounds": self.all_in_bounds,
            "batched_forward_pass_passed": self.batched_forward_pass_passed,
            "padding_mask_loss_valid": self.padding_mask_loss_valid,
            "candidate_a_hash_invariant": self.candidate_a_hash_invariant,
            "candidate_b_hash_invariant": self.candidate_b_hash_invariant,
            "per_sample_records": [asdict(r) for r in self.per_sample_records],
            "notes": self.notes,
        }


def verify_multilingual_model_compatibility(
    model: IgrisDecoderTransformer | None = None,
) -> MultilingualCompatibilityReport:
    """Validate token ingestion, bounds checking, batching, and loss across all languages."""
    # 1. Pre-check tokenizer invariant hashes
    hash_a = hashlib.sha256(CAND_A_PATH.read_bytes()).hexdigest()
    hash_b = hashlib.sha256(CAND_B_PATH.read_bytes()).hexdigest()
    assert hash_a == CAND_A_HASH
    assert hash_b == CAND_B_HASH

    tok_a = load_candidate_a(str(CAND_A_PATH))
    tok_b = load_candidate_b(str(CAND_B_PATH))

    if model is None:
        cfg = get_test_tiny_config()
        model = IgrisDecoderTransformer(cfg)
    model.eval()

    records: list[LanguageCompatibilityRecord] = []
    batch_cand_a_tokens: list[list[int]] = []

    for sample in BENCHMARK_SAMPLES:
        if not sample.text:
            continue

        ids_a = tok_a.encode_content(sample.text)
        ids_b = tok_b.encode_content(sample.text)

        # Check bounds: must be within [0, 32767]
        bounds_a = all(0 <= tid < VOCAB_SIZE for tid in ids_a)
        bounds_b = all(0 <= tid < VOCAB_SIZE for tid in ids_b)
        ids_in_bounds = bounds_a and bounds_b

        # Content tokens should not collide with reserved structural IDs 0..11
        struct_valid_a = all(tid >= STRUCTURAL_COUNT for tid in ids_a)
        struct_valid_b = all(tid >= STRUCTURAL_COUNT for tid in ids_b)
        structural_ids_valid = struct_valid_a and struct_valid_b

        # Assemble sequence with structural BOS (1) and EOS (2)
        seq_a = [1] + ids_a + [2]
        batch_cand_a_tokens.append(seq_a)

        # Single sequence forward pass
        t_seq = torch.tensor([seq_a], dtype=torch.long)
        with torch.no_grad():
            out = model(t_seq, labels=t_seq)
            loss_val = out["loss"].item() if out["loss"] is not None else float("nan")

        records.append(
            LanguageCompatibilityRecord(
                category=sample.category,
                sample_id=sample.sample_id,
                cand_a_token_count=len(ids_a),
                cand_b_token_count=len(ids_b),
                ids_in_bounds=ids_in_bounds,
                structural_ids_valid=structural_ids_valid,
                forward_pass_passed=True,
                loss_finite=(not (torch.isnan(out["loss"]) or torch.isinf(out["loss"]))),
            )
        )

    # 2. Test variable-length batched forward pass with padding
    sample_batch = batch_cand_a_tokens[:8]
    max_len = max(len(seq) for seq in sample_batch)
    bsz = len(sample_batch)

    padded_ids = torch.zeros((bsz, max_len), dtype=torch.long)
    attention_mask = torch.zeros((bsz, max_len), dtype=torch.long)
    labels = torch.full((bsz, max_len), -100, dtype=torch.long)

    for i, seq in enumerate(sample_batch):
        padded_ids[i, : len(seq)] = torch.tensor(seq, dtype=torch.long)
        attention_mask[i, : len(seq)] = 1
        labels[i, : len(seq)] = torch.tensor(seq, dtype=torch.long)

    with torch.no_grad():
        batch_out = model(padded_ids, attention_mask=attention_mask, labels=labels)
        batch_loss = batch_out["loss"].item()

    batched_passed = (
        batch_out["logits"].shape == (bsz, max_len, model.config.vocab_size)
        and not (torch.isnan(batch_out["loss"]) or torch.isinf(batch_out["loss"]))
    )

    # 3. Post-check candidate hash invariants
    post_hash_a = hashlib.sha256(CAND_A_PATH.read_bytes()).hexdigest()
    post_hash_b = hashlib.sha256(CAND_B_PATH.read_bytes()).hexdigest()

    all_in_bounds = all(r.ids_in_bounds for r in records)
    notes = (
        "Multilingual token compatibility certified across English, Hindi, Tamil, Telugu, "
        "Malayalam, Kannada, Bengali, Gujarati, and Tanglish. Forward passes succeed with finite loss. "
        "Note: Language competence requires full pre-training on authorized corpora."
    )

    return MultilingualCompatibilityReport(
        total_samples_evaluated=len(records),
        all_in_bounds=all_in_bounds,
        batched_forward_pass_passed=batched_passed,
        padding_mask_loss_valid=(batch_loss > 0),
        candidate_a_hash_invariant=(post_hash_a == CAND_A_HASH),
        candidate_b_hash_invariant=(post_hash_b == CAND_B_HASH),
        per_sample_records=records,
        notes=notes,
    )


if __name__ == "__main__":
    report = verify_multilingual_model_compatibility()
    print("=== Multilingual Model Compatibility Verification ===")
    print(f"Total samples evaluated: {report.total_samples_evaluated}")
    print(f"All token IDs in bounds [0, 32767]: {report.all_in_bounds}")
    print(f"Batched forward pass with padding: {report.batched_forward_pass_passed}")
    print(f"Candidate A SHA-256 invariant: {report.candidate_a_hash_invariant}")
    print(f"Candidate B SHA-256 invariant: {report.candidate_b_hash_invariant}")
    print(report.notes)
